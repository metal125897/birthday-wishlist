import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
import vm from 'node:vm';
import {readBookmarks, writeBookmarks} from '../dist/assets/bookmarks.js';
let saved;
const storage = {getItem: () => saved, setItem: (_, value) => { saved = value; }};
assert.deepEqual([...readBookmarks(storage)], []);
assert.equal(writeBookmarks(storage, new Set(['gift-a', 'gift-b'])), true);
assert.deepEqual([...readBookmarks(storage)], ['gift-a', 'gift-b']);
assert.equal(writeBookmarks(undefined, new Set(['a'])), false);
saved = '{broken'; assert.equal(readBookmarks(storage).size, 0);
saved = '["a",{"status":"reserved"},null,12,"a"]';
assert.deepEqual([...readBookmarks(storage)], ['a']);
const source = await readFile(new URL('../dist/assets/app.js', import.meta.url), 'utf8');
const state = {bookmarks:new Set()};
const classes = new Set(), attributes = {};
const button = {classList:{toggle(name,on){if(on)classes.add(name);else classes.delete(name);}},setAttribute(name,value){attributes[name]=value;}};
const context = vm.createContext({state});
vm.runInContext(source.slice(source.indexOf('function updateBookmarkButton('), source.indexOf('\nfunction refreshBookmarks')), context);
context.updateBookmarkButton(button,'gift-a');
assert.equal(classes.has('glass-button--quiet'),false);
assert.equal(attributes['aria-pressed'],'false');
state.bookmarks.add('gift-a');context.updateBookmarkButton(button,'gift-a');
assert.equal(classes.has('glass-button--quiet'),true);
assert.equal(attributes['aria-pressed'],'true');
assert.equal(attributes['aria-label'],'Убрать из отложенных');
state.bookmarks.delete('gift-a');context.updateBookmarkButton(button,'gift-a');
assert.equal(classes.has('glass-button--quiet'),false);
assert.equal(attributes['aria-label'],'Отложить подарок');
console.log('Bookmarks: ID-only persistence, deduplication, invalid data and storage failure passed.');
